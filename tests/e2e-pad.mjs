// בדיקת קצה-לקצה ללוח הכתיבה על ה-dist הבנוי (דורש playwright; לא חלק מ-npm test)
import { createRequire } from 'module';
const { chromium } = createRequire(import.meta.url)('playwright');
import { createServer } from 'http'; import { readFileSync, existsSync, statSync } from 'fs'; import { join, extname } from 'path';
const FILE = process.argv[2] || '/mnt/user-data/uploads/חברת החשמל/ריכוז מתקנים ואביזרים - חברת החשמל - מעודכן.xlsx';
const MIME = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.svg': 'image/svg+xml', '.webmanifest': 'application/manifest+json' };
const server = createServer((req, res) => { let f = join('dist', decodeURIComponent(req.url.split('?')[0])); if (!existsSync(f) || statSync(f).isDirectory()) f = 'dist/index.html'; res.setHeader('Content-Type', MIME[extname(f)] || 'application/octet-stream'); res.end(readFileSync(f)); }).listen(4611);
const browser = await chromium.launch();
const context = await browser.newContext({ viewport: { width: 800, height: 1280 }, deviceScaleFactor: 1, locale: 'he-IL', serviceWorkers: 'block' });
const page = await context.newPage();
page.on('pageerror', (e) => console.log('PAGEERROR', e.message));
page.on('dialog', (d) => d.accept());
await page.addInitScript(() => {
  class FakeRecognition { start() { this.onstart?.(); window.__rec = this; } stop() { this.onend?.(); } abort() { this.onend?.(); } }
  window.SpeechRecognition = FakeRecognition; window.webkitSpeechRecognition = FakeRecognition;
  window.say = (text, confidence = 0.9) => window.__rec.onresult({ resultIndex: 0, results: [Object.assign([{ transcript: text, confidence }], { isFinal: true })] });
});
await page.goto('http://localhost:4611/'); await page.waitForTimeout(800);
await page.locator('input[type=file]').setInputFiles({ name: 'ריכוז.xlsx', mimeType: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', buffer: readFileSync(FILE) });
await page.locator('button', { hasText: 'קישון' }).first().click({ timeout: 20000 });
await page.locator('button', { hasText: 'התחל בדיקה' }).click();
await page.locator('button', { hasText: 'התחל האזנה' }).click({ timeout: 20000 });
const say = async (t) => { await page.evaluate((x) => window.say(x), t); await page.waitForTimeout(80); };
const counters = async () => (await page.locator('header').first().innerText()).replace(/\n/g, ' ');
const pad = page.locator('textarea');
const chips = () => page.locator('[aria-label="זוהו בלוח"] span').allInnerTexts();

await say('מיקום מחסן כלים'); await say("סוג רצועה עגולה ירוקה 4 מ'");
if (await page.locator('text=לאיזה סוג הכוונה').count()) await say('1');
await page.locator('button[aria-label="לוח כתיבה"]').click();
const box = await page.locator('section[aria-label="לוח כתיבה"]').boundingBox();
console.log('1 גובה הלוח:', Math.round(box.height / 1280 * 100) + '% מהמסך');
await pad.pressSequentially('2345/3, 2346/3 פסול, 23x?7, K500158', { delay: 5 });
console.log('2 זוהו:', (await chips()).join(' | '));
await page.locator('button', { hasText: /^פסול$/ }).click();
await pad.pressSequentially('7001');
console.log('3 אחרי כפתור פסול:', await pad.inputValue());
await page.screenshot({ path: 'tests/pad-large.png' });
await page.locator('button', { hasText: 'רשום' }).click(); await page.waitForTimeout(100);
console.log('4 אחרי רישום:', await counters(), '· נשאר בלוח:', JSON.stringify(await pad.inputValue()));
await pad.fill('8001, 8002');
await say('מיקום חדש ארובה');
console.log('5 החלפת מיקום בקול:', await counters(), '· לוח:', JSON.stringify(await pad.inputValue()));
await pad.fill('9001, 9002 פסול'); await page.waitForTimeout(500);
await page.reload(); await page.waitForTimeout(1500);
await page.locator('button', { hasText: 'המשך' }).click();
console.log('6 אחרי טעינה מחדש - הלוח נשמר:', JSON.stringify(await pad.inputValue()));
await page.locator('button', { hasText: 'התחל האזנה' }).or(page.locator('button[aria-label="התחל האזנה"]')).first().click();
await say('סוג מחגר כלשהו מיוחד'); await page.waitForTimeout(100);
console.log('7 סוג לא מוכר - הלוח מפנה מקום לשאלה:', await page.locator('text=להוסיף סוג חדש').count() > 0, '· לוח מוצג:', await pad.count() > 0, '·', await counters());
await page.locator('button', { hasText: /^בטל$/ }).click(); await page.waitForTimeout(100);
await page.locator('button[aria-label="הקטן לוח"]').click();
const half = await page.locator('section[aria-label="לוח כתיבה"]').boundingBox();
console.log('8 חצי מסך:', Math.round(half.height / 1280 * 100) + '%');
await pad.fill('9101, 9102, 9103');
await page.screenshot({ path: 'tests/pad-half.png' });
await page.locator('button[aria-label="בטל פעולה אחרונה"]').click(); await page.waitForTimeout(100);
console.log('9 ביטול:', await counters(), '· לוח:', JSON.stringify(await pad.inputValue()));
await page.setViewportSize({ width: 412, height: 915 }); await page.locator('button[aria-label="הגדל לוח"]').click(); await page.waitForTimeout(200);
await page.screenshot({ path: 'tests/pad-phone.png' });
await browser.close(); server.close();
